package ru.pereklichka.domain.time

/**
 * Возраст записи в миллисекундах: сколько прошло с её создания на телефоне автора.
 *
 * Считает его [ageNow]. [approximate] стоит, если телефон перезагружался после получения записи и возраст
 * оценён по настенным часам. Экран тогда пишет «примерно 2 мин назад».
 */
data class Age(val ms: Long, val approximate: Boolean)
